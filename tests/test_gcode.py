"""The plugin reads the slicer's figures as Khayt does (shared vectors from Khayt's docs/)."""

import json
import os
import pathlib
import tempfile
import unittest

from khayt_orca import gcode

VECTORS = pathlib.Path(__file__).parent / "vectors"


class SharedVectors(unittest.TestCase):
    cases = json.loads((VECTORS / "connector.vectors.json").read_text(encoding="utf-8"))["gcodeFilaments"]

    def test_filaments_and_total(self):
        self.assertGreaterEqual(len(self.cases), 9)
        for c in self.cases:
            with self.subTest(c["name"]):
                text = "\n".join(c["lines"])
                self.assertEqual(gcode.filaments(text), c["filaments"])
                got = gcode.filament_grams(text)
                if c["filamentGrams"] is None:
                    self.assertIsNone(got)
                else:
                    self.assertAlmostEqual(got, c["filamentGrams"], places=6)


class Figures(unittest.TestCase):
    def test_time_layers_changes_from_head_and_tail(self):
        head = "; generated by OrcaSlicer 2.5.1\n; total layers count = 120\n"
        tail = "; estimated printing time (normal mode) = 1h 2m 5s\n; total filament change = 3\n" \
               "; filament used [g] = 12.34, 0.00, 2.48\n"
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "big.gcode")
            pathlib.Path(p).write_bytes(head.encode() + b"G1 X1 Y1\n" * 200_000 + tail.encode())
            f = gcode.figures(p)
            self.assertEqual(f["timeSec"], 3725)
            self.assertEqual(f["layers"], 120)
            self.assertEqual(f["toolchanges"], 3)
            self.assertEqual([x["slot"] for x in f["filaments"]], [1, 3])


class CaptureFromFile(unittest.TestCase):
    def test_figures_ride_in_the_capture(self):
        from khayt_orca import capture
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "Plate.gcode")
            pathlib.Path(p).write_text("; total layers count = 7\n; filament used [g] = 1.5\n"
                                       "; estimated printing time (normal mode) = 2m 0s\n", encoding="utf-8")
            c = capture.from_file(p, intent="quote")
            self.assertEqual((c["timeSec"], c["layers"]), (120, 7))
            self.assertEqual(c["filaments"][0]["grams"], 1.5)
