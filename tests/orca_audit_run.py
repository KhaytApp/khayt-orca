"""Counts the permission questions OrcaSlicer 2.5.1 would ask this plugin.

Run in its own process (a Python audit hook cannot be removed): `python -m
tests.orca_audit_run <mode>`; prints one JSON line. `tests/test_orca_permissions.py`
runs it.

The rules copied from Orca 2.5.1 (src/slic3r/plugin/PluginAuditManager.cpp):
- Orca's data folder is an allowed root for reads and writes, create and delete
  included (`install_hook`); the folder of the G-code being exported is a scoped
  root for a G-code step; the Python install is readable. Nothing there asks.
- Anywhere else a read or read/write is asked once per exact path and remembered;
  a create (os.mkdir) or delete (os.remove, os.rmdir) is asked EVERY time, never
  remembered (and refused off the main thread).
- `urllib.Request` is judged by its full URL and remembered for that URL only;
  `http.client.connect` by its host, remembered for the host; the socket events
  under a granted connection are not asked again.

Modes: "plugin" (the plugin as shipped), "home" (storage outside Orca's folder),
"urllib" (requests through urllib), "lazy" (no imports at load, as on Nov 17):
the last three prove the counter bites.
"""

