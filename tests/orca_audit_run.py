granted_hosts = set()
busy = threading.local()


def inside(path, roots):
    p = os.path.realpath(path)
    return any(p == r or p.startswith(r + os.sep) for r in roots)


def ask(kind, target, remember=True):
    key = (kind, target)
    if remember and key in remembered:
        return
    asked.append({"kind": kind, "target": target, "thread": threading.current_thread().name})
    if remember:
        remembered.add(key)


def fs(kind, paths_):
    write = kind != "read"
    for p in paths_:
        if not isinstance(p, (str, bytes, os.PathLike)):
            continue
        p = os.fsdecode(p)
        if p.startswith("/dev/"):
            continue
        if inside(p, RW) or (not write and inside(p, READ_ONLY)):
            continue
        ask("fs-" + kind, os.path.realpath(p), remember=kind in ("read", "readwrite"))


def hook(event, args):
    if getattr(busy, "on", False):
        return
    busy.on = True
    try:
        if event == "import":
            ask("import", str(args[0]), remember=False)
        elif event == "open":
            path, mode, flags = args
            if isinstance(path, int):
                # open() on a file descriptor names no path: Orca asks about the
                # "open" event itself (an event grant), once, remembered.
                ask("fs-event", "open on a file descriptor")
                return
            writes = (mode and any(c in mode for c in "wax+")) or (
                mode is None and flags & (os.O_WRONLY | os.O_RDWR | os.O_CREAT))
            fs("readwrite" if writes else "read", [path])
        elif event in ("os.listdir", "os.scandir"):
            fs("read", [args[0] if args and args[0] is not None else "."])
        elif event == "os.mkdir":
            fs("create", [args[0]])
        elif event in ("os.remove", "os.rmdir"):
            fs("delete", [args[0]])
        elif event in ("os.rename", "shutil.copyfile"):
            fs("readwrite", [args[0], args[1]])
        elif event == "urllib.Request":
            ask("net", "url " + str(args[0]))
        elif event == "http.client.connect":
            host = str(args[1])
            granted_hosts.add(host)
            ask("net", "host " + host)
        elif event in ("socket.connect", "socket.getaddrinfo"):
            target = args[1] if event == "socket.connect" else args[0]
            host = target[0] if isinstance(target, tuple) else target
            if str(host) not in granted_hosts:
                ask("net", "socket " + str(host))
    finally:
        busy.on = False


