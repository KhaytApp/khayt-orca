# -- what the plugin does, on its own threads as in Orca --------------------------
def on_thread(fn):
    out = {}
    def run():
        try:
            out["result"] = fn()
        except Exception as e:  # noqa: BLE001 - the stand-in Mac answers {} to everything
            out["error"] = e
    t = threading.Thread(target=run, name="plugin-worker")
    t.start()
    t.join()
    return out


