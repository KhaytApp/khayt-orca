"""Counts the permission questions OrcaSlicer 2.5.1 would ask this plugin.

Run in its own process (a Python audit hook cannot be removed): `python -m
tests.orca_audit_run <mode>`; prints one JSON line. `tests/test_orca_permissions.py`
runs it.

The rules copied from Orca 2.5.1 (src/slic3r/plugin/PluginAuditManager.cpp):
- Orca's data folder is an allowed root for reads and writes, create and delete
  included (`install_hook`); the folder of the G-code being exported is a scoped
  root for a G-code step; the Python install is readable. Nothing there asks.
- Anywhere else a read or read/write is asked once per exact path and remembered;
  a create (os.mkdir) or delete (os.remove, os.rmdir) is asked EVERY time, never
  remembered (and refused off the main thread).
- `urllib.Request` is judged by its full URL and remembered for that URL only;
  `http.client.connect` by its host, remembered for the host; the socket events
  under a granted connection are not asked again.

Modes: "plugin" (the plugin as shipped), "home" (storage outside Orca's folder),
"urllib" (requests through urllib): the last two prove the counter bites.
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile
import threading

MODE = sys.argv[1] if len(sys.argv) > 1 else "plugin"
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, REPO)

# -- set up before the hook: a fake Orca data folder, a G-code, a stand-in Mac ----
tmp = os.path.realpath(tempfile.mkdtemp())
data = os.path.join(tmp, "OrcaSlicer")
plugin_file = os.path.join(data, "orca_plugins", "khayt_orca-0.1.0-py3-none-any.whl", "__whl_extracted__",
                           "khayt_orca", "khayt_orca", "plugin.py")
os.makedirs(os.path.dirname(plugin_file))
gdir = os.path.join(tmp, "gcode-export")
os.makedirs(gdir)
gcode = os.path.join(gdir, "plate_1.gcode")
with open(gcode, "w") as f:
    f.write("; generated by OrcaSlicer 2.5.1\n; estimated printing time (normal mode) = 1h 2m 3s\nG1 X1 Y1\n" * 50)
home = os.path.join(tmp, "home", ".khayt-orca")

SERVER = r"""
import http.server, sys
class H(http.server.BaseHTTPRequestHandler):
    def _ok(self):
        n = int(self.headers.get('Content-Length') or 0)
        if n: self.rfile.read(n)
        self.send_response(200); self.send_header('Content-Type','application/json')
        self.send_header('Content-Length','2'); self.end_headers(); self.wfile.write(b'{}')
    do_GET = do_POST = do_DELETE = _ok
    def log_message(self, *a): pass
s = http.server.ThreadingHTTPServer(('127.0.0.1', 0), H)
print(s.server_address[1], flush=True)
s.serve_forever()
"""
server = subprocess.Popen([sys.executable, "-c", SERVER], stdout=subprocess.PIPE, text=True)
port = int(server.stdout.readline())
base = f"http://127.0.0.1:{port}"

from khayt_orca import app, pairing, paths  # noqa: E402  (imported before the hook)
from tests.test_app import FakeShop, PAIRED  # noqa: E402

root = home if MODE == "home" else paths.storage_root(here=plugin_file)

# -- the hook ------------------------------------------------------------------
# Python's own bytecode cache: Orca puts it inside its data folder (python/pycache).
READ_ONLY = {os.path.realpath(p) for p in (sys.prefix, sys.base_prefix, REPO, sys.pycache_prefix) if p}
RW = {os.path.realpath(data), os.path.realpath(gdir)}
asked = []
remembered = set()
granted_hosts = set()
busy = threading.local()


def inside(path, roots):
    p = os.path.realpath(path)
    return any(p == r or p.startswith(r + os.sep) for r in roots)


def ask(kind, target, remember=True):
    key = (kind, target)
    if remember and key in remembered:
        return
    asked.append({"kind": kind, "target": target})
    if remember:
        remembered.add(key)


def fs(kind, paths_):
    write = kind != "read"
    for p in paths_:
        if not isinstance(p, (str, bytes, os.PathLike)):
            continue
        p = os.fsdecode(p)
        if p.startswith("/dev/"):
            continue
        if inside(p, RW) or (not write and inside(p, READ_ONLY)):
            continue
        ask("fs-" + kind, os.path.realpath(p), remember=kind in ("read", "readwrite"))


def hook(event, args):
    if getattr(busy, "on", False):
        return
    busy.on = True
    try:
        if event == "open":
            path, mode, flags = args
            if isinstance(path, int):
                return
            writes = (mode and any(c in mode for c in "wax+")) or (
                mode is None and flags & (os.O_WRONLY | os.O_RDWR | os.O_CREAT))
            fs("readwrite" if writes else "read", [path])
        elif event in ("os.listdir", "os.scandir"):
            fs("read", [args[0] if args and args[0] is not None else "."])
        elif event == "os.mkdir":
            fs("create", [args[0]])
        elif event in ("os.remove", "os.rmdir"):
            fs("delete", [args[0]])
        elif event in ("os.rename", "shutil.copyfile"):
            fs("readwrite", [args[0], args[1]])
        elif event == "urllib.Request":
            ask("net", "url " + str(args[0]))
        elif event == "http.client.connect":
            host = str(args[1])
            granted_hosts.add(host)
            ask("net", "host " + host)
        elif event in ("socket.connect", "socket.getaddrinfo"):
            target = args[1] if event == "socket.connect" else args[0]
            host = target[0] if isinstance(target, tuple) else target
            if str(host) not in granted_hosts:
                ask("net", "socket " + str(host))
    finally:
        busy.on = False


FakeShop.calls, FakeShop.queue_answer = [], ({"v": 1, "jobs": []}, "etag-1")
FakeShop.slice_states = [{"state": "in-inbox"}] * 1000
import atexit  # noqa: E402
atexit.register(server.terminate)
sys.addaudithook(hook)

# -- what the plugin does: pair, send, then 10 minutes of the worker's ticks ------
if MODE == "urllib":
    import urllib.request

    def via_urllib(method, url, body=None, headers=None, timeout=10.0):
        req = urllib.request.Request(url, data=body, method=method, headers=headers or {})
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.status, r.read()
    http = via_urllib
else:
    http = pairing._http
http("POST", base + "/api/connectors/pair", b"{}")
for _ in range(5):
    http("GET", base + "/api/connectors/pair/PAIR123")
http("POST", base + "/api/connectors/pair/PAIR123/reveal", b"{}")

c = app.Controller(root, shop_factory=FakeShop)
c.paired = PAIRED
c._save_paired(PAIRED)
c.send(gcode, slicer={"name": "OrcaSlicer", "plugin": "0.1.0"}, printer={"preset": "U1"}, process={"preset": None})
for _ in range(120):               # the worker wakes every 5 s: 10 minutes
    c.deliver()
    c.refresh_queue()
    c.refresh_sent()
    c.view()
c.forget_pairing(tell_the_mac=False)

server.terminate()
print(json.dumps({"mode": MODE,
                  "net": [a for a in asked if a["kind"] == "net"],
                  "fs": [a for a in asked if a["kind"] != "net"]}))
shutil.rmtree(tmp, ignore_errors=True)
